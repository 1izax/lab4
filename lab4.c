#include <stdio.h>
#include <locale.h>

int road()
{
	setlocale(LC_CTYPE, "RUS");

	int A, B;

	printf("=============================================================\n");
	printf("Условие задачи:\n");
	printf("На развилке дорог установлен знак. Он указывает\n");
	printf("направление \"Налево\" только в том случае, когда ровно\n");
	printf("одно из двух чисел (A или B), полученных от датчиков\n");
	printf("traffic flow, окажется чётным. Во всех остальных\n");
	printf("случаях знак указывает направление \"Направо\".\n");
	printf("=============================================================\n");
	printf("Введите показания датчика A:\n");
	scanf("%d", &A);
	printf("Введите показания датчика B:\n");
	scanf("%d", &B);
	printf("=============================================================\n");

	int pa = (A % 2 == 0);
	int pb = (B % 2 == 0);
	int goLeft = (pa != pb);

	printf("Исходные данные:\n");
	printf("Датчик A = %d (%s)\n", A, pa ? "чётное" : "нечётное");
	printf("Датчик B = %d (%s)\n", B, pb ? "чётное" : "нечётное");
	printf("=============================================================\n");
	printf("Результат:\n");
	if (goLeft)
	{
		printf("Ровно одно из чисел чётное.\n");
		printf("Направление: НАЛЕВО\n");
	}
	else
	{
		printf("Числа имеют одинаковую чётность.\n");
		printf("Направление: НАПРАВО\n");
	}
	printf("=============================================================\n");
}

int main()
{
	road();
	getchar();
	return 0;
}